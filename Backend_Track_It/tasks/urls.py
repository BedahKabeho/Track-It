from django.urls import path
from rest_framework.authtoken.views import obtain_auth_token
from .views import (
    AdminStatsView,
    AdminTaskListView,
    AdminUserListView,
    AdminUserRoleUpdateView,
    CurrentUserView,
    LogoutView,
    NotificationListView,
    NotificationReadView,
    RegisterView,
    TaskDetailView,
    TaskListCreateView,
    WorkspaceDetailView,
    WorkspaceListCreateView,
    google_login,
    google_callback,
    github_login,
    github_callback,
)

urlpatterns = [
    path("auth/register/", RegisterView.as_view(), name="register"),
    path("auth/login/", obtain_auth_token, name="login"),
    path("auth/me/", CurrentUserView.as_view(), name="current-user"),
    path("auth/logout/", LogoutView.as_view(), name="logout"),
    path("admin/stats/", AdminStatsView.as_view(), name="admin-stats"),
    path("admin/users/", AdminUserListView.as_view(), name="admin-users"),
    path("admin/users/<int:user_id>/role/", AdminUserRoleUpdateView.as_view(), name="admin-user-role"),
    path("admin/tasks/", AdminTaskListView.as_view(), name="admin-tasks"),
    path("workspaces/", WorkspaceListCreateView.as_view(), name="workspace-list-create"),
    path("workspaces/<int:pk>/", WorkspaceDetailView.as_view(), name="workspace-detail"),
    path("tasks/", TaskListCreateView.as_view(), name="task-list-create"),
    path("tasks/<int:pk>/", TaskDetailView.as_view(), name="task-detail"),
    path("notifications/", NotificationListView.as_view(), name="notification-list"),
    path("notifications/<int:pk>/read/", NotificationReadView.as_view(), name="notification-read"),
    path("auth/google/", google_login, name="oauth-google-login"),
    path("auth/google/callback/", google_callback, name="oauth-google-callback"),
    path("auth/github/", github_login, name="oauth-github-login"),
    path("auth/github/callback/",github_callback, name="oauth-github-callback"),
]
